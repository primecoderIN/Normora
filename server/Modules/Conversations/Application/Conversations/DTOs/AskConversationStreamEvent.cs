using System.Text.Json.Serialization;
using Normora.Modules.Conversations.Application.Conversations.Commands;

namespace Normora.Modules.Conversations.Application.Conversations.DTOs;

/// <summary>
/// Base polymorphic record representing a Server-Sent Event (SSE) streamed during conversation responses.
/// </summary>
[JsonPolymorphic(TypeDiscriminatorPropertyName = "type")]
[JsonDerivedType(typeof(CitationsReadyEvent), "citations")]
[JsonDerivedType(typeof(TextChunkEvent), "text")]
[JsonDerivedType(typeof(ToolStartedEvent), "tool_started")]
[JsonDerivedType(typeof(ToolFinishedEvent), "tool_finished")]
[JsonDerivedType(typeof(ActionCardEvent), "action_card")]
[JsonDerivedType(typeof(StreamFinishedEvent), "finished")]
public abstract record AskConversationStreamEvent;

/// <summary>
/// Event emitted when retrieval citations and source documents have been resolved.
/// </summary>
public sealed record CitationsReadyEvent(
    Guid UserMessageId,
    Guid AssistantMessageId,
    IReadOnlyList<AskConversationCitation> Sources) : AskConversationStreamEvent;

/// <summary>
/// Event emitted for each streamed text delta token generated by the LLM.
/// </summary>
public sealed record TextChunkEvent(string Text) : AskConversationStreamEvent;

/// <summary>
/// Event emitted when an autonomous agent tool starts execution.
/// </summary>
/// <param name="ToolName">The identifier of the tool being executed (e.g. calculate_policy_limit).</param>
/// <param name="ToolCallId">Unique identifier correlating start and finished events for this call.</param>
public sealed record ToolStartedEvent(string ToolName, string ToolCallId) : AskConversationStreamEvent;

/// <summary>
/// Event emitted when an autonomous agent tool completes execution.
/// </summary>
/// <param name="ToolName">The identifier of the tool that executed.</param>
/// <param name="ToolCallId">Correlation identifier matching the ToolStartedEvent.</param>
/// <param name="Success">Whether the tool executed without unhandled errors.</param>
/// <param name="Summary">Short, human-readable summary of the tool output or error.</param>
public sealed record ToolFinishedEvent(string ToolName, string ToolCallId, bool Success, string? Summary = null) : AskConversationStreamEvent;

/// <summary>
/// Event emitted when an agent synthesizes an interactive A2UI action card for the user.
/// </summary>
/// <param name="ActionType">Identifier of the action type (e.g. policy_limit_card, hr_escalation_card).</param>
/// <param name="Title">Headline title for the card.</param>
/// <param name="Description">Descriptive contextual summary.</param>
/// <param name="Parameters">Structured key-value pairs representing action parameters.</param>
/// <param name="ConfirmButtonText">Optional primary CTA button text.</param>
/// <param name="CancelButtonText">Optional secondary/dismiss button text.</param>
public sealed record ActionCardEvent(
    string ActionType,
    string Title,
    string Description,
    IReadOnlyDictionary<string, string> Parameters,
    string? ConfirmButtonText = null,
    string? CancelButtonText = null) : AskConversationStreamEvent;

/// <summary>
/// Event emitted when answer streaming is complete and database persistence has finalized.
/// </summary>
public sealed record StreamFinishedEvent() : AskConversationStreamEvent;
