using System.Text.Json.Serialization;
using Normora.Modules.Conversations.Application.Commands;

namespace Normora.Modules.Conversations.Application.Dtos;

/// <summary>
/// Base polymorphic record representing a Server-Sent Event (SSE) streamed during conversation responses.
/// </summary>
[JsonPolymorphic(TypeDiscriminatorPropertyName = "type")]
[JsonDerivedType(typeof(CitationsReadyEvent), "citations")]
[JsonDerivedType(typeof(TextChunkEvent), "text")]
[JsonDerivedType(typeof(StreamFinishedEvent), "finished")]
public abstract record AskConversationStreamEvent;

/// <summary>
/// Event emitted when retrieval citations and source documents have been resolved.
/// </summary>
public sealed record CitationsReadyEvent(
    Guid UserMessageId,
    Guid AssistantMessageId,
    IReadOnlyList<AskConversationCitation> Sources) : AskConversationStreamEvent;

/// <summary>
/// Event emitted for each streamed text delta token generated by the LLM.
/// </summary>
public sealed record TextChunkEvent(string Text) : AskConversationStreamEvent;

/// <summary>
/// Event emitted when answer streaming is complete and database persistence has finalized.
/// </summary>
public sealed record StreamFinishedEvent() : AskConversationStreamEvent;
