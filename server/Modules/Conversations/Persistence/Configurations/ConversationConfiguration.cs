using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Normora.Modules.Conversations.Domain;
using Normora.Shared.Interfaces;

namespace Normora.Modules.Conversations.Persistence.Configurations;

/// <summary>
/// Entity Framework Core mapping configuration for the root Conversation entity.
/// Manages conversational chat threads between employees and the AI assistant within an organization.
/// </summary>
public class ConversationConfiguration : IEntityTypeConfiguration<Conversation>
{
    public void Configure(EntityTypeBuilder<Conversation> builder)
    {
        // Primary Key:
        builder.HasKey(c => c.Id);

        // Thread Title:
        // Automatically generated by AutoTitleService using asynchronous background LLM summarization.
        // Capped at 200 characters to ensure responsive sidebar rendering.
        builder.Property(c => c.Title).IsRequired().HasMaxLength(200);

        // Multi-Tenant Isolation Index:
        // B-Tree index on TenantId ensures queries for tenant metrics and cross-organization isolation stay fast.
        builder.HasIndex(c => c.TenantId);

        // User Thread Ownership Index:
        // B-Tree index on UserId powers the employee's conversation history sidebar with sub-millisecond retrieval.
        builder.HasIndex(c => c.UserId);
    }
}

